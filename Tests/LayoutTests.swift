import Foundation
@main struct LayoutTests {
 @MainActor static func main() throws {
    let root = URL(fileURLWithPath: CommandLine.arguments[1])
    try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
    let layout = PaneLayout(root: root)
    layout.resetAll()
    func check(_ result: Bool, _ name: String) { precondition(result, name); print("PASS \(name)") }
    let defaults = layout.widths(total: 1380, libraryVisible: true, right: .tutor)
    check(defaults.library == 240 && defaults.right == 400 && defaults.reader == 724, "default proportions")
    layout.adjust(.library, by: 80, total: 1380, libraryVisible: true, right: .tutor)
    layout.adjust(.tutor, by: 60, total: 1380, libraryVisible: true, right: .tutor)
    let resized = layout.widths(total: 1380, libraryVisible: true, right: .tutor)
    check(abs(resized.library - 320) < 0.01 && abs(resized.right - 460) < 0.01, "independent pane changes")
    layout.save()
    let reloaded = PaneLayout(root: root)
    check(abs(reloaded.ratio(.library) - 320.0/1380) < 0.0001 && abs(reloaded.ratio(.tutor) - 460.0/1380) < 0.0001, "persistent ratios")
    let narrow = layout.widths(total: 1160, libraryVisible: true, right: .tutor)
    check(narrow.reader >= 519.999 && narrow.library >= 200 && narrow.right >= 320, "narrow window minimums")
    check(abs(narrow.library + narrow.reader + narrow.right + 16 - 1160) < 0.01, "no layout overflow")
    let wide = layout.widths(total: 1600, libraryVisible: true, right: .tutor)
    check(abs(wide.right/1600 - resized.right/1380) < 0.0001, "resizing window keeps proportions")
    layout.adjust(.tutor, by: 10000, total: 1380, libraryVisible: true, right: .tutor)
    check(abs(layout.widths(total: 1380, libraryVisible: true, right: .tutor).reader - 520) < 0.01, "drag cannot squeeze reader")
    layout.adjust(.tutor, by: -10000, total: 1380, libraryVisible: true, right: .tutor)
    check(layout.widths(total: 1380, libraryVisible: true, right: .tutor).right == 320, "drag minimum")
    let notesBefore = layout.ratio(.notes)
    layout.adjust(.notes, by: 40, total: 1380, libraryVisible: true, right: .notes)
    check(layout.ratio(.notes) != notesBefore && layout.widths(total: 1380, libraryVisible: true, right: .tutor).right == 320, "notes and tutor independent")
    let hidden = layout.widths(total: 1160, libraryVisible: false, right: nil)
    check(hidden.library == 0 && hidden.right == 0 && hidden.reader == 1160, "hidden panes release all space")
    layout.resetAll()
    layout.adjust(.tutor, by: 180, total: 1380, libraryVisible: true, right: .tutor)
    let compressed = layout.widths(total: 1160, libraryVisible: true, right: .tutor)
    layout.adjust(.tutor, by: -20, total: 1160, libraryVisible: true, right: .tutor)
    let afterCompressedDrag = layout.widths(total: 1160, libraryVisible: true, right: .tutor)
    check(abs(afterCompressedDrag.library - compressed.library) < 0.01 && abs(afterCompressedDrag.right - (compressed.right - 20)) < 0.01, "drag in constrained window preserves opposite edge")
    let libraryBefore = layout.ratio(.library)
    layout.reset(.tutor)
    check(layout.ratio(.library) == libraryBefore && layout.ratio(.tutor) == PaneLayout.Ratios().tutor, "single divider reset")
    layout.resetAll()
    check(layout.ratio(.library) == PaneLayout.Ratios().library && layout.ratio(.notes) == PaneLayout.Ratios().notes, "reset all")
    try Data("{invalid}".utf8).write(to:root.appendingPathComponent("layout.json"))
    check(PaneLayout(root: root).ratio(.library) == PaneLayout.Ratios().library, "corrupted preferences fallback")
 }
}
